; ============================================================================
; DISK OPERATIONS - Заглушки
; ============================================================================
module disk_ops

DISK_ERROR_NOT_IMPLEMENTED equ 0xFF

; ----------------------------------------------------------------------------
; disk_read - Чтение секторов с диска
; Вход: A = номер диска (0-3)
;       BC:DE = LBA адрес
;       HL = буфер для данных
;       IY = количество секторов
; Выход: A = код ошибки (0=успех)
; ----------------------------------------------------------------------------
PUBLIC _disk_read
_disk_read:
disk_read_:
    ld a, DISK_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; disk_write - Запись секторов на диск
; Вход: A = номер диска
;       BC:DE = LBA адрес
;       HL = буфер с данными
;       IY = количество секторов
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _disk_write
_disk_write:
disk_write_:
    ld a, DISK_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; disk_get_status - Получить статус диска
; Вход: A = номер диска
; Выход: A = статус (биты: 0=готов, 1=защита от записи, 7=ошибка)
; ----------------------------------------------------------------------------
PUBLIC _disk_get_status
_disk_get_status:
disk_get_status_:
    ld a, 0x01  ; Заглушка: диск готов
    ret

; ----------------------------------------------------------------------------
; disk_get_info - Получить информацию о диске
; Вход: A = номер диска
;       HL = буфер для информации (16 байт)
; Выход: Буфер заполнен структурой DISK_INFO
; ----------------------------------------------------------------------------
PUBLIC _disk_get_info
_disk_get_info:
disk_get_info_:
