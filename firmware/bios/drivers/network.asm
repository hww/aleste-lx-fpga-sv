; ============================================================================
; NETWORK DRIVER - Заглушки
; ============================================================================
module network

NET_ERROR_NOT_IMPLEMENTED equ 0xFF

; ----------------------------------------------------------------------------
; net_init - Инициализация сетевого стека
; Вход: Нет
; Выход: A = код ошибки (0=успех)
; ----------------------------------------------------------------------------
PUBLIC _net_init
_net_init:
net_init_:
    xor a  ; Заглушка: всегда успех
    ret

; ----------------------------------------------------------------------------
; net_send - Отправить пакет
; Вход: HL = указатель на данные
;       DE = длина данных
;       BC = адрес назначения (IP:порт или MAC)
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _net_send
_net_send:
net_send_:
    ld a, NET_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; net_receive - Получить пакет
; Вход: HL = буфер для данных
;       DE = размер буфера
;       BC = буфер для информации об отправителе
; Выход: A = код ошибки, DE = длина полученных данных
; ----------------------------------------------------------------------------
PUBLIC _net_receive
_net_receive:
net_receive_:
    ld a, NET_ERROR_NOT_IMPLEMENTED
    ld de, 0
    ret

; ----------------------------------------------------------------------------
; net_get_ip - Получить IP адрес системы
; Вход: HL = буфер для IP (4 байта)
; Выход: Буфер заполнен
; ----------------------------------------------------------------------------
PUBLIC _net_get_ip
_net_get_ip:
net_get_ip_:
    ; Заполняем адресом 127.0.0.1
    ld (hl), 127
    inc hl
    ld (hl), 0
    inc hl
    ld (hl), 0
    inc hl
    ld (hl), 1
    xor a  ; Успех
    ret

; ----------------------------------------------------------------------------
; net_set_ip - Установить IP адрес
; Вход: HL = указатель на IP (4 байта)
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _net_set_ip
_net_set_ip:
net_set_ip_:
    ld a, NET_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; net_connect - Установить соединение
; Вход: HL = указатель на структуру соединения
; Выход: A = дескриптор соединения (0xFF=ошибка)
; ----------------------------------------------------------------------------
PUBLIC _net_connect
_net_connect:
net_connect_:
    ld a, 0xFF  ; Заглушка: ошибка
    ret