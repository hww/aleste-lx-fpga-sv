; ----------------------------------------------------------------------------
; fs_get_free_space - Получить свободное место на диске
; Вход: A = номер диска
;       HL = указатель на 64-битную переменную для результата
; Выход: HL указывает на заполненное значение
; ----------------------------------------------------------------------------
PUBLIC _fs_get_free_space
_fs_get_free_space:
fs_get_free_space_:
    ; Заполняем максимальным значением
    ld b, 8
    ld a, 0xFF
loop_space_:
    ld (hl), a
    inc hl
    djnz loop_space_
    xor a  ; Успех
    ret