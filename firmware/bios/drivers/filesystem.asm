; ============================================================================
; FILESYSTEM - Заглушки
; ============================================================================
module filesystem

FS_ERROR_NOT_IMPLEMENTED equ 0xFF

; ----------------------------------------------------------------------------
; fs_open - Открыть файл
; Вход: HL = указатель на имя файла (ASCIIZ)
;       B = режим открытия (0=чтение, 1=запись, 2=чтение/запись)
; Выход: A = дескриптор файла (0xFF=ошибка)
; ----------------------------------------------------------------------------
PUBLIC _fs_open
_fs_open:
fs_open_:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_close - Закрыть файл
; Вход: A = дескриптор файла
; Выход: A = код ошибки (0=успех)
; ----------------------------------------------------------------------------
PUBLIC _fs_close
_fs_close:
fs_close_:
    xor a  ; Заглушка: всегда успех
    ret

; ----------------------------------------------------------------------------
; fs_read - Чтение из файла
; Вход: A = дескриптор файла
;       HL = буфер для данных
;       DE = количество байт для чтения
; Выход: A = код ошибки, DE = количество прочитанных байт
; ----------------------------------------------------------------------------
PUBLIC _fs_read
_fs_read:
fs_read_:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ld de, 0
    ret

; ----------------------------------------------------------------------------
; fs_write - Запись в файл
; Вход: A = дескриптор файла
;       HL = буфер с данными
;       DE = количество байт для записи
; Выход: A = код ошибки, DE = количество записанных байт
; ----------------------------------------------------------------------------
PUBLIC _fs_write
_fs_write:
fs_write_:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ld de, 0
    ret

; ----------------------------------------------------------------------------
; fs_seek - Перемещение указателя в файле
; Вход: A = дескриптор файла
;       BC:DE = смещение (64-битное)
;       H = режим (0=от начала, 1=от текущей позиции, 2=от конца)
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_seek
_fs_seek:
fs_seek_:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_tell - Получить текущую позицию в файле
; Вход: A = дескриптор файла
;       HL = указатель на 64-битную переменную для результата
; Выход: HL указывает на заполненную позицию
; ----------------------------------------------------------------------------
PUBLIC _fs_tell
_fs_tell:
fs_tell_:
    ; Заполняем нулями
    ld b, 8
    xor a
loop_tell_:
    ld (hl), a
    inc hl
    djnz loop_tell_
    ret

; ----------------------------------------------------------------------------
; fs_delete - Удалить файл
; Вход: HL = указатель на имя файла
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_delete
_fs_delete:
fs_delete_:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_rename - Переименовать файл
; Вход: HL = указатель на старое имя
;       DE = указатель на новое имя
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_rename
_fs_rename:
