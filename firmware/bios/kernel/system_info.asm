; ============================================================================
; SYSTEM INFORMATION - Заглушки
; ============================================================================
module system_info

; ----------------------------------------------------------------------------
; get_version - Получить версию системы
; Выход: HL = версия (старший байт = major, младший = minor)
; ----------------------------------------------------------------------------
PUBLIC _get_version
_get_version:
get_version_:
    ld hl, 0x0100  ; Версия 1.0
    ret

; ----------------------------------------------------------------------------
; get_memory_info - Получить информацию о памяти
; Вход: HL = указатель на структуру MEMORY_INFO
; Выход: Структура заполнена
; ----------------------------------------------------------------------------
PUBLIC _get_memory_info
_get_memory_info:
get_memory_info_:
    ; Заполняем тестовыми данными
    ld (hl), 0x00    ; total_pages
    inc hl
    ld (hl), 0x40    ; 64 страницы
    inc hl
    ld (hl), 0x00    ; free_pages
    inc hl
    ld (hl), 0x20    ; 32 свободные страницы
    inc hl
    ; ... остальные поля нулями
    ld b, 12
    xor a
loop_mem_:
    ld (hl), a
    inc hl
    djnz loop_mem_
    ret

; ----------------------------------------------------------------------------
; get_cpu_info - Получить информацию о процессоре
; Вход: HL = указатель на структуру CPU_INFO
; Выход: Структура заполнена
; ----------------------------------------------------------------------------
PUBLIC _get_cpu_info
_get_cpu_info:
get_cpu_info_:
    ; Заполняем тестовыми данными
    ld (hl), 'Z'
    inc hl
    ld (hl), '8'
    inc hl
    ld (hl), '0'
    inc hl
    ld (hl), 0x04    ; 4 МГц
    inc hl
    ; ... остальные поля
    ld b, 12
    xor a
loop_cpu_:
    ld (hl), a
    inc hl
    djnz loop_cpu_
    ret

; ----------------------------------------------------------------------------
; get_time - Получить текущее время
; Выход: B = часы (0-23)
;        C = минуты (0-59)
;        D = секунды (0-59)
; ----------------------------------------------------------------------------
PUBLIC _get_time
_get_time:
get_time_:
    ld bc, 0x0000  ; 00:00:00
    ld d, 0
    ret

