; ----------------------------------------------------------------------------
; reboot - Перезагрузить систему
; Вход: Нет
; Выход: Не возвращается
; ----------------------------------------------------------------------------
PUBLIC _reboot
_reboot:
reboot_:
    jp 0x0000  ; Заглушка: прыжок на начало

; ----------------------------------------------------------------------------
; shutdown - Выключить систему
; Вход: Нет
; Выход: Не возвращается
; ----------------------------------------------------------------------------
PUBLIC _shutdown
_shutdown:
shutdown_:
    halt  ; Заглушка: останавливаем процессор
    jr shutdown_