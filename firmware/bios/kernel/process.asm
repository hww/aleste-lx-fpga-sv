; proc_yield - Передать управление следующему процессу
; Вход: Нет
; Выход: Нет
; ----------------------------------------------------------------------------
PUBLIC _proc_yield
_proc_yield:
proc_yield_:
    ret  ; Заглушка: просто возвращаемся

