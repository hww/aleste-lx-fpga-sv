module process

PROC_ERROR_NO_MEMORY equ 0x01
PROC_ERROR_INVALID_ID equ 0x02

; ----------------------------------------------------------------------------
; proc_create - Создать новый процесс
; Вход: HL = точка входа
;       BC = размер стека
;       DE = аргумент для процесса
; Выход: A = ID процесса (0=ошибка)
; ----------------------------------------------------------------------------
PUBLIC _proc_create
_proc_create:
proc_create_:
    xor a  ; Заглушка: возвращаем 0 (ошибка)
    ret

; ----------------------------------------------------------------------------
; proc_kill - Завершить процесс
; Вход: A = ID процесса
; Выход: A = код ошибки (0=успех)
; ----------------------------------------------------------------------------
PUBLIC _proc_kill
_proc_kill:
proc_kill_:
    ld a, PROC_ERROR_INVALID_ID
    ret

; ----------------------------------------------------------------------------
; proc_suspend - Приостановить процесс
; Вход: A = ID процесса
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _proc_suspend
_proc_suspend:
proc_suspend_:
    ld a, PROC_ERROR_INVALID_ID
    ret

; ----------------------------------------------------------------------------
; proc_resume - Возобновить процесс
; Вход: A = ID процесса
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _proc_resume
_proc_resume:
proc_resume_:
    ld a, PROC_ERROR_INVALID_ID
    ret

; ----------------------------------------------------------------------------
; proc_get_info - Получить информацию о процессе
; Вход: A = ID процесса
;       HL = буфер для информации
; Выход: Буфер заполнен
; ----------------------------------------------------------------------------
PUBLIC _proc_get_info
_proc_get_info:
proc_get_info_:
    ; Заполняем нулями
    ld b, 32
    xor a
