; ============================================================================
; FILESYSTEM & DISK DRIVERS
; ============================================================================
module fs_drivers

; ---- КОНСТАНТЫ ОШИБОК ----
DISK_ERROR_NOT_IMPLEMENTED equ 0xFF
FS_ERROR_NOT_IMPLEMENTED   equ 0xFF

; ==================== ДИСКОВЫЕ ОПЕРАЦИИ ====================

; ----------------------------------------------------------------------------
; disk_read - Чтение секторов с диска
; Вход: A = номер диска (0-3)
;       BC:DE = LBA адрес
;       HL = буфер для данных
;       IY = количество секторов
; Выход: A = код ошибки (0=успех)
; ----------------------------------------------------------------------------
PUBLIC _disk_read
_disk_read:
    ld a, DISK_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; disk_write - Запись секторов на диск
; Вход: A = номер диска
;       BC:DE = LBA адрес
;       HL = буфер с данными
;       IY = количество секторов
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _disk_write
_disk_write:
    ld a, DISK_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; disk_get_status - Получить статус диска
; Вход: A = номер диска
; Выход: A = статус (биты: 0=готов, 1=защита от записи, 7=ошибка)
; ----------------------------------------------------------------------------
PUBLIC _disk_get_status
_disk_get_status:
    ld a, 0x01  ; Заглушка: диск готов
    ret

; ----------------------------------------------------------------------------
; disk_get_info - Получить информацию о диске
; Вход: A = номер диска
;       HL = буфер для информации (16 байт)
; Выход: Буфер заполнен структурой DISK_INFO
; ----------------------------------------------------------------------------
PUBLIC _disk_get_info
_disk_get_info:
    ; Заполняем нулями
    ld b, 16
    xor a
@loop_info:
    ld (hl), a
    inc hl
    djnz @loop_info
    ret

; ----------------------------------------------------------------------------
; disk_format - Форматирование диска
; Вход: A = номер диска
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _disk_format
_disk_format:
    ld a, DISK_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; disk_seek - Перемещение головки
; Вход: A = номер диска
;       BC:DE = LBA адрес
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _disk_seek
_disk_seek:
    ld a, DISK_ERROR_NOT_IMPLEMENTED
    ret

; ==================== ФАЙЛОВАЯ СИСТЕМА ====================

; ----------------------------------------------------------------------------
; fs_open - Открыть файл
; Вход: HL = указатель на имя файла (ASCIIZ)
;       B = режим открытия (0=чтение, 1=запись, 2=чтение/запись)
; Выход: A = дескриптор файла (0xFF=ошибка)
; ----------------------------------------------------------------------------
PUBLIC _fs_open
_fs_open:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_close - Закрыть файл
; Вход: A = дескриптор файла
; Выход: A = код ошибки (0=успех)
; ----------------------------------------------------------------------------
PUBLIC _fs_close
_fs_close:
    xor a  ; Заглушка: всегда успех
    ret

; ----------------------------------------------------------------------------
; fs_read - Чтение из файла
; Вход: A = дескриптор файла
;       HL = буфер для данных
;       DE = количество байт для чтения
; Выход: A = код ошибки, DE = количество прочитанных байт
; ----------------------------------------------------------------------------
PUBLIC _fs_read
_fs_read:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ld de, 0
    ret

; ----------------------------------------------------------------------------
; fs_write - Запись в файл
; Вход: A = дескриптор файла
;       HL = буфер с данными
;       DE = количество байт для записи
; Выход: A = код ошибки, DE = количество записанных байт
; ----------------------------------------------------------------------------
PUBLIC _fs_write
_fs_write:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ld de, 0
    ret

; ----------------------------------------------------------------------------
; fs_seek - Перемещение указателя в файле
; Вход: A = дескриптор файла
;       BC:DE = смещение (64-битное)
;       H = режим (0=от начала, 1=от текущей позиции, 2=от конца)
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_seek
_fs_seek:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_tell - Получить текущую позицию в файле
; Вход: A = дескриптор файла
;       HL = указатель на 64-битную переменную для результата
; Выход: HL указывает на заполненную позицию
; ----------------------------------------------------------------------------
PUBLIC _fs_tell
_fs_tell:
    ; Заполняем нулями
    ld b, 8
    xor a
@loop_tell:
    ld (hl), a
    inc hl
    djnz @loop_tell
    ret

; ----------------------------------------------------------------------------
; fs_delete - Удалить файл
; Вход: HL = указатель на имя файла
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_delete
_fs_delete:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_rename - Переименовать файл
; Вход: HL = указатель на старое имя
;       DE = указатель на новое имя
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_rename
_fs_rename:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_get_attr - Получить атрибуты файла
; Вход: HL = указатель на имя файла
;       DE = указатель на структуру атрибутов
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_get_attr
_fs_get_attr:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_set_attr - Установить атрибуты файла
; Вход: HL = указатель на имя файла
;       DE = указатель на структуру атрибутов
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_set_attr
_fs_set_attr:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_get_free_space - Получить свободное место на диске
; Вход: A = номер диска
;       HL = указатель на 64-битную переменную для результата
; Выход: HL указывает на заполненное значение
; ----------------------------------------------------------------------------
PUBLIC _fs_get_free_space
_fs_get_free_space:
    ; Заполняем максимальным значением
    ld b, 8
    ld a, 0xFF
@loop_space:
    ld (hl), a
    inc hl
    djnz @loop_space
    xor a  ; Успех
    ret

; ----------------------------------------------------------------------------
; fs_mount - Монтировать файловую систему
; Вход: A = номер диска
;       B = тип ФС (0=FAT16, 1=FAT32, 2=EXT2)
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_mount
_fs_mount:
    ld a, FS_ERROR_NOT_IMPLEMENTED
    ret

; ----------------------------------------------------------------------------
; fs_unmount - Размонтировать файловую систему
; Вход: A = номер диска
; Выход: A = код ошибки
; ----------------------------------------------------------------------------
PUBLIC _fs_unmount
_fs_unmount:
    xor a  ; Всегда успех для заглушки
    ret