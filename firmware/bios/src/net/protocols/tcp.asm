; ----------------------------------------------------------------------------
; tcp_connect - Установить TCP соединение
; Вход: A = номер слота соединения
; ----------------------------------------------------------------------------
tcp_connect:
    push af
    push bc
    push de
    push hl
    push ix
    
    ; Получаем параметры соединения
    call get_connection_params
    
    ; Создаем SYN пакет
    call tcp_create_syn
    
    ; Отправляем SYN
    call tcp_send_packet
    
    ; Устанавливаем состояние
    ld a, TCP_STATE_SYN_SENT
    call set_connection_state
    
    ; Запускаем таймер
    call start_tcp_timer
    
    pop ix
    pop hl
    pop de
    pop bc
    pop af
    ret

; ----------------------------------------------------------------------------
; tcp_disconnect - Закрыть TCP соединение
; Вход: A = номер слота соединения
; ----------------------------------------------------------------------------
tcp_disconnect:
    push af
    push bc
    push de
    push hl
    
    ; Получаем текущее состояние
    call get_connection_state
    cp TCP_STATE_ESTABLISHED
    jr nz, .not_established
    
    ; Создаем FIN пакет
    call tcp_create_fin
    
    ; Отправляем FIN
    call tcp_send_packet
    
    ; Устанавливаем состояние
    ld a, TCP_STATE_FIN_WAIT_1
    call set_connection_state
    
.not_established:
    pop hl
    pop de
    pop bc
    pop af
    ret

; ----------------------------------------------------------------------------
; tcp_send_data - Отправить данные через TCP
; Вход: A = номер слота, HL = данные, DE = длина
; ----------------------------------------------------------------------------
tcp_send_data:
    push af
    push bc
    push de
    push hl
    push ix
    
    ; Сохраняем параметры
    ld (tcp_data_ptr), hl
    ld (tcp_data_len), de
    
    ; Создаем TCP сегмент с данными
    call tcp_create_data_segment
    
    ; Отправляем пакет
    call tcp_send_packet
    
    ; Обновляем номер последовательности
    call update_sequence_number
    
    pop ix
    pop hl
    pop de
    pop bc
    pop af
    ret

; ----------------------------------------------------------------------------
; tcp_receive_data - Получить данные через TCP
; Вход: A = номер слота, HL = буфер, DE = размер
; Выход: DE = количество полученных байт
; ----------------------------------------------------------------------------
tcp_receive_data:
    push af
    push bc
    push hl
    push ix
    
    ; Проверяем, есть ли данные в буфере
    call has_tcp_data
    or a
    jr z, .no_data
    
    ; Читаем данные из буфера
    call read_tcp_data
    
    ; Обновляем номер подтверждения
    call update_ack_number
    
    jr .exit

.no_data:
    ld de, 0

.exit:
    pop ix
    pop hl
    pop bc
    pop af
    ret

; ----------------------------------------------------------------------------
; tcp_timer_handler - Обработчик TCP таймеров
; ----------------------------------------------------------------------------
tcp_timer_handler:
    push af
    push bc
    push hl
    
    ld b, 8
    ld hl, tcp_timers
    
.timer_loop:
    ld a, (hl)
    or a
    jr z, .next_timer
    
    ; Уменьшаем таймер
    dec (hl)
    jr nz, .next_timer
    
    ; Таймер истек
    push bc
    push hl
    
    ; Вычисляем номер соединения
    ld a, 8
    sub b
    
    ; Обрабатываем таймаут
    call handle_tcp_timeout
    
    pop hl
    pop bc

.next_timer:
    inc hl
    djnz .timer_loop
    
    pop hl
    pop bc
    pop af
    ret

