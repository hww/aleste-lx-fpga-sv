; ----------------------------------------------------------------------------
; ip_send - Отправить IP пакет
; Вход: HL = данные, DE = длина, A = протокол, BC = IP назначения
; ----------------------------------------------------------------------------
ip_send:
    push af
    push bc
    push de
    push hl
    
    ; Создаем IP заголовок
    call ip_create_header
    
    ; Отправляем пакет
    call ip_send_packet
    
    pop hl
    pop de
    pop bc
    pop af
    ret

; ----------------------------------------------------------------------------
; ip_receive - Обработать входящий IP пакет
; ----------------------------------------------------------------------------
ip_receive:
    push af
    push bc
    push de
    push hl
    
    ; Проверяем заголовок
    call ip_check_header
    
    ; Определяем протокол
    call ip_get_protocol
    
    ; Передаем соответствующему обработчику
    cp IP_PROTOCOL_TCP
    jr z, .handle_tcp
    
    cp IP_PROTOCOL_UDP
    jr z, .handle_udp
    
    cp IP_PROTOCOL_ICMP
    jr z, .handle_icmp
    
    ; Неизвестный протокол
    jr .exit

.handle_tcp:
    call tcp_handle_packet
    jr .exit
    
.handle_udp:
    call udp_handle_packet
    jr .exit
    
.handle_icmp:
    call icmp_handle_packet

.exit:
    pop hl
    pop de
    pop bc
    pop af
    ret

